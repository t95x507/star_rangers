// a text with {placeholders} filled in
export const questFill = (s, ctx) => String(s).replace(/\{(\w+)\}/g, (m, k) => (ctx[k] != null ? ctx[k] : m));

function clamp(Q, p) {
  for (const k in Q.params) {
    const d = Q.params[k];
    if (typeof p[k] !== 'number') continue;
    if (d.max != null) p[k] = Math.min(d.max, p[k]);
    p[k] = Math.max(d.min ?? 0, p[k]);
  }
}
function failNode(Q, p) {
  for (const k in Q.params) {
    const f = Q.params[k].fail;
    if (!f) continue;
    if ((f.le != null && p[k] <= f.le) || (f.ge != null && p[k] >= f.ge) || (f.lt != null && p[k] < f.lt)) return f.node;
  }
  return null;
}
function apply(run, fx) {
  if (!fx) return;
  if (typeof fx === 'function') fx(run.p, run.ctx);
  else for (const k in fx) run.p[k] = (run.p[k] || 0) + fx[k];
  clamp(QUESTS[run.id], run.p);
}
function enter(run, id) {
  const Q = QUESTS[run.id];
  for (let guard = 0; guard < 6; guard++) {
    run.node = id;
    apply(run, Q.nodes[id].fx);
    const f = !Q.nodes[id].end && failNode(Q, run.p);
    if (!f || f === id) return;
    id = f;
  }
}

export function questStart(id, ctx) {
  const Q = QUESTS[id];
  const p = {};
  for (const k in Q.params) p[k] = Q.params[k].start ?? 0;
  const run = { id, ctx, p, node: null };
  enter(run, Q.start);
  return run;
}
export const questNode = run => QUESTS[run.id].nodes[run.node];
export const questText = run => { const n = questNode(run); return questFill(typeof n.text === 'function' ? n.text(run.p, run.ctx) : n.text, run.ctx); };
export const questChoices = run => (questNode(run).choices || []).filter(c => !c.if || c.if(run.p));
export function questChoose(run, i) {
  const c = questChoices(run)[i];
  if (!c) return;
  apply(run, c.fx);
  const f = failNode(QUESTS[run.id], run.p);
  enter(run, f || (typeof c.to === 'function' ? c.to(run.p) : c.to));
}
// the parameters to show: [name, value text]
export function questParams(run) {
  const Q = QUESTS[run.id], out = [];
  for (const k in Q.params) {
    const d = Q.params[k];
    if (!d.name) continue;
    out.push([d.name, run.p[k] + (d.unit || '') + (d.showMax ? ' / ' + d.max : ''), !!d.fail]);
  }
  return out;
}
